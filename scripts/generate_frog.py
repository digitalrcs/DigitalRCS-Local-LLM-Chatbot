"""Generate original frog artwork as embedded drawing operations and SVG previews.
No downloaded images, fonts, XiaoKe artwork, or runtime asset downloads.
"""
from pathlib import Path
import math
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"docs/images"
OUT.mkdir(parents=True,exist_ok=True)
BG="#102d29"; GREEN="#87c979"; LIGHT="#d6efac"; DARK="#163c30"; CREAM="#fff6d9"; PINK="#ed9d83"
scenes={}
for mood in ("idle","blink","listening","thinking","thinking2","speaking","speaking2","happy","error","setup"):
    ops=[]
    def ellipse(x,y,rx,ry,color): ops.append((0,x,y,rx,ry,color))
    def line(x,y,x2,y2,color): ops.append((1,x,y,x2,y2,color))
    # Pond shadow, broad cheeks, raised eye lobes, soft muzzle.
    ellipse(160,180,105,9,"#0b211f")
    ellipse(160,116,107,68,DARK); ellipse(160,112,103,65,GREEN)
    ellipse(107,63,42,43,DARK); ellipse(213,63,42,43,DARK)
    ellipse(107,60,38,40,GREEN); ellipse(213,60,38,40,GREEN)
    ellipse(160,135,77,35,LIGHT)
    for x in (107,213):
        if mood=="blink" or mood=="happy":
            for k in range(-20,21):
                y=62+int((k*k)/80) if mood=="happy" else 69
                ellipse(x+k,y,2,2,DARK)
        else:
            ellipse(x,61,28,30,CREAM)
            dx=7 if mood in ("thinking","thinking2") else 0
            dy=-7 if mood in ("thinking","thinking2") else 0
            if mood=="thinking2": dx=-7
            rad=14 if mood=="listening" else 12
            ellipse(x+dx,65+dy,rad,17,DARK)
            ellipse(x+dx-4,58+dy,4,5,"#ffffff")
            ellipse(x+dx+5,70+dy,2,2,LIGHT)
    ellipse(82,121,15,8,PINK); ellipse(238,121,15,8,PINK)
    ellipse(149,112,3,2,DARK); ellipse(171,112,3,2,DARK)
    if mood in ("speaking","speaking2"):
        height=20 if mood=="speaking" else 10
        ellipse(160,144,32,height,DARK); ellipse(160,150,18,max(3,height-11),PINK)
    elif mood=="error":
        for k in range(-27,28): ellipse(160+k,148-int(10*(1-(k/27)**2)),2,2,DARK)
        line(84,37,119,45,DARK); line(201,45,236,37,DARK)
    elif mood=="thinking" or mood=="thinking2":
        for k in range(29): ellipse(149+k,144+int(k/8),2,2,DARK)
        for i in range(3): ellipse(270+i*14,44,3 if i!= (0 if mood=="thinking" else 2) else 5,3 if i!= (0 if mood=="thinking" else 2) else 5,LIGHT)
    else:
        width=42 if mood=="happy" else 34
        for k in range(-width,width+1): ellipse(160+k,138+int(13*(1-(k/width)**2)),2,2,DARK)
    if mood=="listening":
        for side in (-1,1):
            for i in range(3):
                x=160+side*(123+i*9); line(x,101-i*6,x,119+i*6,LIGHT)
    if mood=="setup":
        ellipse(273,55,17,17,LIGHT)
        line(273,45,273,58,DARK); ellipse(273,64,2,2,DARK)
    scenes[mood]=ops

def rgb565(color):
    n=int(color[1:],16); return ((n>>19)&31)<<11|((n>>10)&63)<<5|((n>>3)&31)
header=["// SPDX-License-Identifier: MIT", "// Generated by scripts/generate_frog.py. Original DigitalRCS artwork.","#pragma once", "#include <stdint.h>","namespace FrogArt {", "struct Shape { uint8_t kind; int16_t x,y,a,b; uint16_t color; };",f"constexpr uint16_t background=0x{rgb565(BG):04x};"]
for mood,ops in scenes.items():
    header.append(f"const Shape {mood}[] = {{")
    for kind,x,y,a,b,color in ops: header.append(f"{{{kind},{x},{y},{a},{b},0x{rgb565(color):04x}}},")
    header.append("};")
    svg=[f'<svg xmlns="http://www.w3.org/2000/svg" width="320" height="200" viewBox="0 0 320 200"><rect width="320" height="200" fill="{BG}"/>']
    for kind,x,y,a,b,color in ops:
        if kind==0: svg.append(f'<ellipse cx="{x}" cy="{y}" rx="{a}" ry="{b}" fill="{color}"/>')
        else: svg.append(f'<line x1="{x}" y1="{y}" x2="{a}" y2="{b}" stroke="{color}" stroke-width="2"/>')
    svg.append('</svg>'); (OUT/f'frog-{mood}.svg').write_text(''.join(svg))
header.append('}')
(ROOT/'firmware/Franky/FrogArt.h').write_text('\n'.join(header)+'\n')
print('Generated ten original frog poses and matching LCD drawing data.')
